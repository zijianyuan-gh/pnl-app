// Builds Daybook.app (macOS) from the production web build.
//   node scripts/build-mac.mjs            → on macOS: universal Daybook.app + Daybook-mac.zip in release/
//   node scripts/build-mac.mjs --host     → any OS: a binary for the current machine (for testing)
// Requires `bun` on PATH (CI uses oven-sh/setup-bun). The web app must be built first with base "/".
import { execFileSync } from 'node:child_process';
import { cpSync, mkdirSync, readdirSync, rmSync, statSync, writeFileSync, readFileSync, existsSync } from 'node:fs';
import { join, relative } from 'node:path';

const root = new URL('..', import.meta.url).pathname;
const dist = join(root, 'dist');
const out = join(root, 'release');
const host = process.argv.includes('--host');
const pkg = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'));
const run = (cmd, args, opts = {}) => execFileSync(cmd, args, { stdio: 'inherit', cwd: root, ...opts });

if (!existsSync(join(dist, 'index.html'))) throw new Error('dist/ missing — run `npm run build` first');
if (readFileSync(join(dist, 'index.html'), 'utf8').includes('/pnl-app/')) throw new Error('dist/ was built with a sub-path; rebuild with base "/"');

// 1. Embed every file of dist/ into the binary
const files = [];
(function walk(d) {
  for (const n of readdirSync(d)) {
    const p = join(d, n);
    if (statSync(p).isDirectory()) walk(p);
    else if (!n.startsWith('_')) files.push(relative(dist, p).split('\\').join('/'));
  }
})(dist);
mkdirSync(join(root, 'mac/.generated'), { recursive: true });
writeFileSync(
  join(root, 'mac/.generated/assets.ts'),
  `// generated by scripts/build-mac.mjs — do not edit\n` +
    files.map((f, i) => `import f${i} from '../../dist/${f}' with { type: 'file' };`).join('\n') +
    `\nexport const assets: Record<string, string> = {\n` +
    files.map((f, i) => `  ${JSON.stringify(f)}: f${i},`).join('\n') +
    `\n};\n`,
);

rmSync(out, { recursive: true, force: true });
mkdirSync(out, { recursive: true });
const compile = (target, file) =>
  run('bun', ['build', 'mac/server.ts', '--compile', '--minify', ...(target ? [`--target=${target}`] : []), '--outfile', file]);

if (host) {
  compile(null, join(out, 'daybook'));
  console.log(`built ${join(out, 'daybook')}`);
  process.exit(0);
}

// 2. Universal binary (Apple silicon + Intel)
if (process.platform !== 'darwin') throw new Error('the .app bundle is assembled on macOS (lipo, iconutil, codesign)');
compile('bun-darwin-arm64', join(out, 'daybook-arm64'));
compile('bun-darwin-x64', join(out, 'daybook-x64'));
const app = join(out, 'Daybook.app');
mkdirSync(join(app, 'Contents/MacOS'), { recursive: true });
mkdirSync(join(app, 'Contents/Resources'), { recursive: true });
run('lipo', ['-create', '-output', join(app, 'Contents/MacOS/daybook'), join(out, 'daybook-arm64'), join(out, 'daybook-x64')]);
rmSync(join(out, 'daybook-arm64'));
rmSync(join(out, 'daybook-x64'));

// 3. Icon
const iconset = join(out, 'AppIcon.iconset');
mkdirSync(iconset);
for (const s of [16, 32, 128, 256, 512]) {
  run('sips', ['-z', String(s), String(s), 'public/icons/icon-512.png', '--out', join(iconset, `icon_${s}x${s}.png`)], { stdio: 'ignore' });
  run('sips', ['-z', String(s * 2), String(s * 2), 'public/icons/icon-512.png', '--out', join(iconset, `icon_${s}x${s}@2x.png`)], { stdio: 'ignore' });
}
run('iconutil', ['-c', 'icns', iconset, '-o', join(app, 'Contents/Resources/AppIcon.icns')]);
rmSync(iconset, { recursive: true });

// 4. Info.plist — background app (no Dock icon); the UI is the browser window
writeFileSync(
  join(app, 'Contents/Info.plist'),
  `<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0"><dict>
  <key>CFBundleName</key><string>Daybook</string>
  <key>CFBundleDisplayName</key><string>Daybook</string>
  <key>CFBundleIdentifier</key><string>io.github.zijianyuan-gh.daybook</string>
  <key>CFBundleVersion</key><string>${pkg.version}</string>
  <key>CFBundleShortVersionString</key><string>${pkg.version}</string>
  <key>CFBundleExecutable</key><string>daybook</string>
  <key>CFBundleIconFile</key><string>AppIcon</string>
  <key>CFBundlePackageType</key><string>APPL</string>
  <key>LSMinimumSystemVersion</key><string>11.0</string>
  <key>LSUIElement</key><true/>
</dict></plist>
`,
);

// 5. Ad-hoc signature (required to run on Apple silicon) and zip
run('codesign', ['--force', '--deep', '--sign', '-', app]);
run('codesign', ['--verify', '--deep', '--strict', app]);
run('ditto', ['-c', '-k', '--keepParent', app, join(out, 'Daybook-mac.zip')]);
console.log(`built ${app} and ${join(out, 'Daybook-mac.zip')}`);
